import AppKit
#if SWIFT_PACKAGE
import ShitieCore
#endif
import SwiftUI

struct SettingsView: View {
    @ObservedObject var model: AppModel
    @State private var limitText = "1000"
    @State private var limitError: String?
    @State private var showingClear = false

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 24) {
                Text("设置").font(.title2.weight(.semibold))
                GroupBox("自动记录") {
                    VStack(alignment: .leading, spacing: 10) {
                        Toggle("记录复制的文字和网页链接", isOn: Binding(get: { !model.settings.isPaused }, set: { _ in model.togglePause() }))
                            .disabled(!model.isReady || model.isChangingPause)
                        Text("关闭主窗口后继续记录。暂停期间及恢复前已有的内容不会补录。")
                            .font(.callout).foregroundStyle(.secondary)
                    }.padding(10).frame(maxWidth: .infinity, alignment: .leading)
                }
                GroupBox("历史记录") {
                    VStack(alignment: .leading, spacing: 12) {
                        HStack {
                            Text("记录上限")
                            TextField("1000", text: $limitText).textFieldStyle(.roundedBorder).frame(width: 105)
                                .accessibilityLabel("历史记录上限").onSubmit { applyLimit() }
                            Text("条").foregroundStyle(.secondary)
                            Spacer()
                            Button("应用") { applyLimit() }.disabled(!model.isReady)
                        }
                        if let limitError { Text(limitError).font(.caption).foregroundStyle(.red) }
                        Text("默认 1000 条。超出上限时，按最近复制时间清理最旧的记录。降低上限会立即执行清理。")
                            .font(.callout).foregroundStyle(.secondary)
                        Divider()
                        HStack {
                            Text("共 \(model.totalCount) 条").font(.callout).foregroundStyle(.secondary)
                            Spacer()
                            Button("清空历史记录…", role: .destructive) { showingClear = true }.disabled(!model.isReady)
                        }
                    }.padding(10)
                }
                GroupBox("隐私与内容范围") {
                    VStack(alignment: .leading, spacing: 10) {
                        Text("所有内容只保存在本机，不连接账号或网络服务。数据库未额外加密，请使用 macOS 登录保护与 FileVault 保护本机。")
                        Text("跳过带有 Concealed、Transient、AutoGenerated 等通用标记及已知 1Password 类型的剪贴板。不会向密码管理器请求内容；仅依靠剪贴板标记无法识别所有密码或敏感信息，复制敏感内容前请暂停记录。")
                        Text("只保存纯文本表示和 HTTP/HTTPS 链接；跳过文件和图片，不保存富文本格式。单条最多 1 MiB，超限会提示并整条跳过，绝不截断。")
                    }.font(.callout).foregroundStyle(.secondary).padding(10)
                }
                GroupBox("关于拾贴") {
                    VStack(alignment: .leading, spacing: 8) {
                        HStack(spacing: 10) {
                            Image(nsImage: NSApplication.shared.applicationIconImage)
                                .resizable().interpolation(.high).frame(width: 40, height: 40)
                                .accessibilityHidden(true)
                            Text("拾贴 1.0.0").font(.headline)
                        }
                        Text("轻巧、清晰、快速、本地优先。\n复制过的，随时找回。")
                            .font(.callout).foregroundStyle(.secondary)
                        Text("数据位置").font(.caption.weight(.semibold)).padding(.top, 4)
                        Text(HistoryRepository.defaultURL.path).font(.system(size: 11, design: .monospaced))
                            .textSelection(.enabled).foregroundStyle(.secondary)
                    }.padding(10).frame(maxWidth: .infinity, alignment: .leading)
                }
                if let issue = model.issue { Text(issue).font(.callout).foregroundStyle(.red).textSelection(.enabled) }
            }.padding(24)
        }.frame(width: 560, height: 660).accentColor(.teal)
            .onAppear { limitText = String(model.settings.limit) }
            .onChange(of: model.settings.limit) { limitText = String($0) }
            .sheet(isPresented: $showingClear) { ClearHistorySheet(model: model) }
    }

    private func applyLimit() {
        guard let value = Int(limitText), (1...100_000).contains(value) else {
            limitError = "请输入 1 至 100,000 之间的整数。"; return
        }
        limitError = nil
        model.setLimit(value)
    }
}

private struct ClearHistorySheet: View {
    @ObservedObject var model: AppModel
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        VStack(alignment: .leading, spacing: 18) {
            Label("清空历史记录？", systemImage: "trash").font(.headline)
            Text("此操作会删除全部历史记录和未保存的修改，无法撤销。自定义分类会保留。清空后，新复制的内容仍会按当前记录状态保存。")
                .font(.callout).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
            HStack {
                Spacer()
                Button("取消", role: .cancel) { dismiss() }.keyboardShortcut(.cancelAction)
                Button("清空历史", role: .destructive) {
                    model.clearHistory()
                    dismiss()
                }
            }
        }.padding(24).frame(width: 390)
    }
}
